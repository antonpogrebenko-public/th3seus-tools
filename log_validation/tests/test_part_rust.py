"""The Rust text emitted for the hitl-physics part tables and the hitl-daemon parser aliases."""

from __future__ import annotations

import dataclasses

import pytest

from log_validation.part_rows import STATUS_CANDIDATE, PartTables, build_part_tables
from log_validation.part_rust import (
    ALIASES_FILE, RUST_FILES, emit_daemon_aliases, emit_part_source, emit_rust_files, rust_f64)
from log_validation.tests.part_fakes import BARO_OK, MAG_OK, noise_entry

RUN = "2026-11-05"
IMU_M = {"gyro.gyro_noise_density": 1.234e-3, "accel.accel_noise_density": 2.5e-2}
EMPTY = build_part_tables([])


def bmi088_tables(n=40):
    return build_part_tables(
        [noise_entry(f"l{i}", f"v{i}", IMU_M, imu="BMI088") for i in range(n)])


def _gps_entries(name, n, **extra):
    m = {"gps.eph_median_m": 0.7, "gps.epv_median_m": 1.1, "gps.speed_accuracy_median_m_s": 0.04,
         "gps.update_rate_hz": 9.0, "gps.fix_type_mode": 3.0, **extra}
    return [noise_entry(f"g{i}", f"gv{i}", m, gps=name) for i in range(n)]


def _hand_candidate(part, name):
    """A candidate row with a proposal, built from the empty tables' Other row."""
    other = next(r for r in EMPTY.rows if r.part == part and r.variant == "Other")
    row = dataclasses.replace(other, variant=name, status=STATUS_CANDIDATE, log_names=("X",),
                              vehicles=12, proposed=1.0)
    return PartTables(rows=EMPTY.rows + (row,), log_ids=())


def test_rust_f64():
    assert [rust_f64(x) for x in (1.234e-3, 0.025, 1.2345678e-5, 5.0, 123456.0, 1.5e-4)] == \
        ["0.001234", "0.025", "1.235e-5", "5.0", "1.235e5", "0.00015"]
    assert [rust_f64(x) for x in (0.0, 1e-5, 1e20, -2.5e-6)] == ["0.0", "1e-5", "1e20", "-2.5e-6"]


def test_rust_f64_rounding_and_extremes():
    assert rust_f64(9.9996) == "10.0"
    assert rust_f64(1.23456e-300) == "1.235e-300"
    assert rust_f64(-0.0) == "-0.0"


@pytest.mark.parametrize("bad", [float("nan"), float("inf"), float("-inf")])
def test_rust_f64_rejects_non_finite(bad):
    with pytest.raises(ValueError):
        rust_f64(bad)


def test_file_names():
    assert RUST_FILES == {"imu": "imu_chip.rs", "baro": "baro_chip.rs", "mag": "mag_chip.rs",
                          "gps": "gps_chipset.rs"}
    assert ALIASES_FILE == "daemon_aliases.rs"
    assert set(emit_rust_files(EMPTY, RUN)) == {*RUST_FILES.values(), ALIASES_FILE}


def test_new_imu_variant():
    files = emit_rust_files(bmi088_tables(), RUN)
    imu = files["imu_chip.rs"]
    assert "    Lsm6dso,\n    Bmi088,\n    Other,\n}" in imu
    assert ("            // PX4 log names BMI088; new in run 2026-11-05\n"
            "            ImuChip::Bmi088 => ImuProfile {\n"
            "                // was 8.726646e-4 (Other); median of 40 vehicles, run 2026-11-05\n"
            "                gyro_noise_density: 0.001234,\n"
            "                // was 6.37e-3 (Other); median of 40 vehicles, run 2026-11-05\n"
            "                accel_noise_density: 0.025,\n"
            "                gyro_bias_sigma: 1e-4,\n"
            "                gyro_bias_tau: 100.0,\n"
            "            },\n") in imu
    assert '        "bmi088" => ImuChip::Bmi088,\n' in files["daemon_aliases.rs"]


def test_part_file_layout_follows_build_rs():
    imu = emit_part_source("imu", EMPTY, RUN)
    assert "#[derive(Debug, Clone, PartialEq, Eq)]\npub enum ImuChip {\n    Mpu6000,\n" in imu
    assert ("impl ImuChip {\n    /// Datasheet-derived noise profile for this IMU chipset.\n"
            "    ///\n    /// Sources: InvenSense") in imu
    assert "    pub fn imu_profile(&self) -> ImuProfile {\n        match self {\n" in imu
    assert imu.endswith("        }\n    }\n}\n")
    assert imu.startswith("// Generated by log_validation.part_tables, run 2026-11-05: ImuChip")
    assert "hitl-physics 0.13.1" in imu


def test_existing_entry_with_a_proposal():
    entries = [noise_entry(f"l{i}", f"v{i}", {"gyro.gyro_noise_density": 1.5e-4}, imu="ICM42688P")
               for i in range(10)]
    imu = emit_part_source("imu", build_part_tables(entries), RUN)
    assert ("                // was 4.88e-5 (hitl-physics 0.13.1); median of 10 vehicles, run 2026-11-05\n"
            "                gyro_noise_density: 0.00015,\n") in imu
    # the unmeasured accel field of that entry keeps its value and has no "was" comment
    assert "                accel_noise_density: 6.86e-4,\n" in imu


def test_entry_without_a_proposal_keeps_its_value():
    imu = emit_part_source("imu", build_part_tables([]), RUN)
    assert ("            // Slightly noisier than MPU6000\n"
            "            ImuChip::Mpu6500 => ImuProfile {\n"
            "                gyro_noise_density: 9.4e-4,\n") in imu
    assert "// was" not in imu


def test_candidate_without_a_proposal_has_no_variant():
    files = emit_rust_files(bmi088_tables(n=9), RUN)
    assert "Bmi088" not in files["imu_chip.rs"]
    assert "bmi088" not in files[ALIASES_FILE]


def test_empty_tables_are_the_0_13_1_structure():
    imu = emit_part_source("imu", EMPTY, RUN)
    assert "            ImuChip::Other => ImuChip::Mpu6000.imu_profile(),\n" in imu
    gps = emit_part_source("gps", EMPTY, RUN)
    assert "            GpsChipset::Other => GpsChipset::UbloxM8N.gps_profile(),\n" in gps
    baro = emit_part_source("baro", EMPTY, RUN)
    assert ("            // best in class\n"
            "            BaroChip::Dps310 => BaroProfile {\n"
            "                noise_sigma_m: 0.05,\n"
            "            },\n") in baro
    assert ("            BaroChip::Other => BaroProfile {\n"
            "                noise_sigma_m: 0.15,\n            },\n") in baro


def test_other_with_a_proposal_gets_explicit_literals():
    entries = [noise_entry(f"l{i}", f"v{i}", {"gyro.gyro_noise_density": 2e-4}) for i in range(10)]
